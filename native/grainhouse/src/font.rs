/// Width of `text` in pixels at `dot` pixels per dot (one dot between letters).
pub fn width(text: &str, dot: f32) -> f32 {
    text.chars().count() as f32 * 6.0 * dot - dot
}

/// Draws text with its top-left at (x, y), `dot` pixels per font dot, blended at `alpha` with a soft glow
/// (0 = none) like light on film or a screen.
pub fn draw(img: &mut Image, text: &str, x: f32, y: f32, dot: f32, colour: [f32; 3], alpha: f32, glow: f32) {
    let (tw, th) = (width(text, dot), 7.0 * dot);
    let pad = (dot * 3.0) as isize;
    let x0 = (x as isize - pad).max(0) as usize;
    let y0 = (y as isize - pad).max(0) as usize;
    let x1 = ((x + tw) as usize + pad as usize).min(img.w);
    let y1 = ((y + th) as usize + pad as usize).min(img.h);
    if x1 <= x0 || y1 <= y0 {
        return;
    }
    let (bw, bh) = (x1 - x0, y1 - y0);
    let mut a = vec![0f32; bw * bh];
    for (i, c) in text.chars().enumerate() {
        let Some(g) = glyph(c) else { continue };
        let gx = x + i as f32 * 6.0 * dot;
        for (row, bits) in g.iter().enumerate() {
            for (col, b) in bits.bytes().enumerate() {
                if b != b'1' {
                    continue;
                }
                let (px0, py0) = (gx + col as f32 * dot, y + row as f32 * dot);
                for py in py0 as usize..((py0 + dot).ceil() as usize) {
                    for px in px0 as usize..((px0 + dot).ceil() as usize) {
                        if px >= x0 && px < x1 && py >= y0 && py < y1 {
                            a[(py - y0) * bw + px - x0] = 1.0;
                        }
                    }
                }
            }
        }
    }
    let mut g = a.clone();
    if glow > 0.0 {
        gaussian(&mut g, bw, bh, ((dot * 0.8) as usize).max(1));
    }
    for yy in 0..bh {
        for xx in 0..bw {
            let k = ((a[yy * bw + xx] + if glow > 0.0 { g[yy * bw + xx] * glow } else { 0.0 }).min(1.0)) * alpha;
            if k <= 0.0 {
                continue;
            }
            let i = (y0 + yy) * img.w + x0 + xx;
            let p = img.px[i];
            let v = [((p >> 16) & 255) as f32, ((p >> 8) & 255) as f32, (p & 255) as f32];
            let o = [0, 1, 2].map(|c| (v[c] + (colour[c] * 255.0 - v[c]) * k).clamp(0.0, 255.0) as u32);
            img.px[i] = (o[0] << 16) | (o[1] << 8) | o[2];
        }
    }
}
